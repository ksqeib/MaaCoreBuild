<#
.SYNOPSIS
    Build the Maa FastDeploy fork from source into the MaaCoreBuild deps layout.

.DESCRIPTION
    MaaCore's OCR integration tracks the MaaXYZ/FastDeploy `dev` branch, which
    contains APIs (PPOCRv6, WebGPU hooks, detector postprocessor setters) that
    are not present in the old fastdeploy-v1 binary bundle.

    This script configures FastDeploy in a small wrapper project so the produced
    DLL is named `fastdeploy_ppocr_maa.dll`, builds Release + Debug, and stages:

        include/fastdeploy/...
        include/Eigen, include/eigen3, include/nlohmann
        lib/fastdeploy_ppocr.lib
        bin/fastdeploy_ppocr_maa.dll
        bin/DirectML.dll
        debug/lib/fastdeploy_ppocr.lib
        debug/bin/fastdeploy_ppocr_maa.dll
        share/fastdeploy_ppocr/fastdeploy_ppocrConfig.cmake

    The staging tree can be passed to tools/pack-fastdeploy.ps1.

    -BuildDepsRoot must contain OpenCV, ONNXRuntime, Eigen and DirectML, i.e. a
    normal assembled deps/ tree (or a MaaDeps installed tree). The import
    libraries must use the `_maa` DLL names so the resulting FastDeploy DLL
    depends on opencv_world4_maa.dll / onnxruntime_maa.dll.

.EXAMPLE
    powershell -File .\tools\build-fastdeploy.ps1 `
        -FastDeploySrc D:\self\maa\FastDeploy `
        -BuildDepsRoot D:\self\maa\MaaCoreBuild\.work\MaaCore\deps `
        -OutputDir D:\self\maa\MaaCoreBuild\.fastdeploy-stage
#>
param(
    [string]$RepoRoot = (Resolve-Path (Join-Path $PSScriptRoot "..")).Path,
    [string]$FastDeploySrc = "",
    [string]$BuildDepsRoot = "",
    [string]$OutputDir = "",
    [string]$Generator = "",
    [int]$Parallel = 8
)

$ErrorActionPreference = "Stop"

if ([string]::IsNullOrWhiteSpace($FastDeploySrc)) {
    throw "-FastDeploySrc is required (path to the MaaXYZ/FastDeploy checkout)."
}
if ([string]::IsNullOrWhiteSpace($BuildDepsRoot)) {
    throw "-BuildDepsRoot is required (an assembled deps/ tree with OpenCV/ORT/Eigen)."
}
if ([string]::IsNullOrWhiteSpace($OutputDir)) {
    $OutputDir = Join-Path $RepoRoot ".fastdeploy-stage"
}

$FastDeploySrc = (Resolve-Path $FastDeploySrc).Path
$BuildDepsRoot = (Resolve-Path $BuildDepsRoot).Path

foreach ($required in @(
        (Join-Path $FastDeploySrc "CMakeLists.txt"),
        (Join-Path $FastDeploySrc "fastdeploy\vision\ocr\ppocr\ppocr_v6.h"),
        (Join-Path $BuildDepsRoot "include\opencv4"),
        (Join-Path $BuildDepsRoot "lib\opencv_world4.lib"),
        (Join-Path $BuildDepsRoot "include\onnxruntime"),
        (Join-Path $BuildDepsRoot "lib\onnxruntime.lib"),
        (Join-Path $BuildDepsRoot "include\Eigen"))) {
    if (-not (Test-Path $required)) {
        throw "Missing build input: $required"
    }
}

function Invoke-External {
    param([string]$FilePath, [string[]]$Arguments)
    & $FilePath @Arguments
    if ($LASTEXITCODE -ne 0) {
        throw "Command failed: $FilePath $($Arguments -join ' ')"
    }
}

function Get-MsvcDumpbin {
    $vswhere = Join-Path ${env:ProgramFiles(x86)} "Microsoft Visual Studio\Installer\vswhere.exe"
    if (-not (Test-Path $vswhere)) {
        return ""
    }
    $installationPath = & $vswhere -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
    if ($LASTEXITCODE -ne 0 -or [string]::IsNullOrWhiteSpace($installationPath)) {
        return ""
    }
    $toolsRoot = Join-Path $installationPath "VC\Tools\MSVC"
    if (-not (Test-Path $toolsRoot)) {
        return ""
    }
    $toolset = Get-ChildItem $toolsRoot -Directory | Sort-Object Name -Descending | Select-Object -First 1
    if ($null -eq $toolset) {
        return ""
    }
    return (Join-Path $toolset.FullName "bin\Hostx64\x64\dumpbin.exe")
}

$workRoot = Join-Path ([System.IO.Path]::GetTempPath()) ("maa-fastdeploy-" + [Guid]::NewGuid().ToString("N"))
$wrapperSrc = Join-Path $workRoot "src"
$buildDir = Join-Path $workRoot "build"
New-Item -ItemType Directory -Path $wrapperSrc -Force | Out-Null

try {
    $fastDeploySrcCmake = $FastDeploySrc -replace '\\', '/'
    @"
cmake_minimum_required(VERSION 3.20)
project(fastdeploy_maa LANGUAGES CXX)
if(NOT DEFINED FASTDEPLOY_SRC)
    message(FATAL_ERROR "FASTDEPLOY_SRC is required")
endif()
add_subdirectory("`${FASTDEPLOY_SRC}" fastdeploy)
# The Maa loader expects the historical _maa name; the import library is
# generated by the linker and therefore references the same renamed DLL.
set_target_properties(fastdeploy_ppocr PROPERTIES OUTPUT_NAME "fastdeploy_ppocr_maa")
"@ | Set-Content (Join-Path $wrapperSrc "CMakeLists.txt") -NoNewline

    $configureArgs = @(
        "-S", $wrapperSrc,
        "-B", $buildDir,
        "-DFASTDEPLOY_SRC=$fastDeploySrcCmake",
        "-DCMAKE_PREFIX_PATH=$BuildDepsRoot",
        "-DBUILD_SHARED_LIBS=ON"
    )
    if (-not [string]::IsNullOrWhiteSpace($Generator)) {
        $configureArgs += @("-G", $Generator)
    }
    if ([string]::IsNullOrWhiteSpace($Generator) -or $Generator -like "Visual Studio*") {
        $configureArgs += @("-A", "x64")
    }

    Write-Host "==> Configure FastDeploy"
    Write-Host "    source: $FastDeploySrc"
    Write-Host "    deps:   $BuildDepsRoot"
    Invoke-External "cmake" $configureArgs

    foreach ($config in @("Release", "Debug")) {
        Write-Host "==> Build FastDeploy ($config)"
        Invoke-External "cmake" @("--build", $buildDir, "--config", $config, "--parallel", [string]$Parallel)
    }

    $releaseDir = Join-Path $buildDir "fastdeploy\Release"
    $debugDir = Join-Path $buildDir "fastdeploy\Debug"
    $releaseDll = Join-Path $releaseDir "fastdeploy_ppocr_maa.dll"
    $releaseLib = Join-Path $releaseDir "fastdeploy_ppocr_maa.lib"
    $debugDll = Join-Path $debugDir "fastdeploy_ppocr_maa.dll"
    $debugLib = Join-Path $debugDir "fastdeploy_ppocr_maa.lib"

    foreach ($file in @($releaseDll, $releaseLib, $debugDll, $debugLib)) {
        if (-not (Test-Path $file)) {
            throw "FastDeploy build did not produce $file"
        }
    }

    $dumpbin = Get-MsvcDumpbin
    if (-not [string]::IsNullOrWhiteSpace($dumpbin)) {
        $dependencies = & $dumpbin /nologo /dependents $releaseDll
        if ($LASTEXITCODE -ne 0) {
            throw "dumpbin failed for $releaseDll"
        }
        foreach ($expected in @("opencv_world4_maa.dll", "onnxruntime_maa.dll")) {
            if (-not ($dependencies -match [regex]::Escape($expected))) {
                throw "FastDeploy was linked against the wrong OpenCV/ORT names; expected dependency $expected. Check -BuildDepsRoot import libraries."
            }
        }
    }

    Write-Host "==> Stage FastDeploy deps tree"
    if (Test-Path $OutputDir) {
        Remove-Item $OutputDir -Recurse -Force
    }
    foreach ($dir in @("include", "lib", "bin", "debug\lib", "debug\bin", "share\fastdeploy_ppocr")) {
        New-Item -ItemType Directory -Path (Join-Path $OutputDir $dir) -Force | Out-Null
    }

    Get-ChildItem (Join-Path $FastDeploySrc "fastdeploy") -Recurse -File -Filter "*.h" | ForEach-Object {
        $relative = $_.FullName.Substring($FastDeploySrc.Length).TrimStart('\', '/')
        $destination = Join-Path $OutputDir (Join-Path "include" $relative)
        New-Item -ItemType Directory -Path (Split-Path -Parent $destination) -Force | Out-Null
        Copy-Item -LiteralPath $_.FullName -Destination $destination -Force
    }

    foreach ($extra in @("Eigen", "eigen3", "nlohmann")) {
        $source = Join-Path $BuildDepsRoot "include\$extra"
        if (Test-Path $source) {
            Copy-Item -LiteralPath $source -Destination (Join-Path $OutputDir "include\$extra") -Recurse -Force
        }
    }

    Copy-Item -LiteralPath $releaseDll -Destination (Join-Path $OutputDir "bin\fastdeploy_ppocr_maa.dll") -Force
    Copy-Item -LiteralPath $releaseLib -Destination (Join-Path $OutputDir "lib\fastdeploy_ppocr.lib") -Force
    Copy-Item -LiteralPath $debugDll -Destination (Join-Path $OutputDir "debug\bin\fastdeploy_ppocr_maa.dll") -Force
    Copy-Item -LiteralPath $debugLib -Destination (Join-Path $OutputDir "debug\lib\fastdeploy_ppocr.lib") -Force

    foreach ($directml in @(
            (Join-Path $BuildDepsRoot "bin\DirectML.dll"),
            (Join-Path $BuildDepsRoot "DirectML.dll"))) {
        if (Test-Path $directml) {
            Copy-Item -LiteralPath $directml -Destination (Join-Path $OutputDir "bin\DirectML.dll") -Force
            break
        }
    }
    if (-not (Test-Path (Join-Path $OutputDir "bin\DirectML.dll"))) {
        throw "DirectML.dll was not found under $BuildDepsRoot"
    }

    Copy-Item -LiteralPath (Join-Path $PSScriptRoot "..\cmake\upstream\fastdeploy_ppocrConfig.cmake") `
        -Destination (Join-Path $OutputDir "share\fastdeploy_ppocr\fastdeploy_ppocrConfig.cmake") -Force

    Write-Host ""
    Write-Host "FastDeploy staging tree ready: $OutputDir"
    Write-Host "  source commit: $(git -C $FastDeploySrc rev-parse HEAD 2>$null)"
    Write-Host "  release DLL:   $([Math]::Round((Get-Item $releaseDll).Length / 1MB, 1)) MB"
    Write-Host "  debug DLL:     $([Math]::Round((Get-Item $debugDll).Length / 1MB, 1)) MB"
}
finally {
    Remove-Item -LiteralPath $workRoot -Recurse -Force -ErrorAction SilentlyContinue
}
